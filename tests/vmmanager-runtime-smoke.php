#!/usr/bin/env php
<?php
declare(strict_types=1);
require dirname(__DIR__).'/core/autoload.php';
use Cajeer\Servers\Connector\{VmmanagerConnector,HttpsTransport,ConnectorContext,ConnectorResult,EndpointPolicy,ConnectorTransportException};
use Cajeer\Servers\Integration\ConnectorRegistry;
use Cajeer\Servers\Http\Exception\HttpException;
$n=0;
$ok=static function(bool $condition,string $label)use(&$n):void {if (!$condition) throw new RuntimeException('FAIL: '.$label); $n++;};
$reject=static function(callable $call,?string $code=null)use($ok):void {try{$call();}catch(Throwable $e){$ok($code===null||($e instanceof HttpException&&$e->errorCode===$code),'expected rejection');return;}throw new RuntimeException('Expected rejection');};
$driver=new VmmanagerConnector(new HttpsTransport(new EndpointPolicy([],null,true)));
$manifest=$driver->manifest(); $registry=new ConnectorRegistry($driver);
$ok($manifest->supports('validate_rotation')&&$manifest->accepts('vmmanager_api','api')&&$manifest->accepts('api_token','api'),'manifest accepts real API credentials');
$nodes=[['id'=>1,'name'=>'node-a','state'=>'active'],['id'=>'2','name'=>'node-b','maintenance_mode'=>true]];
$hosts=[['id'=>123,'name'=>'guest','state'=>true,'node'=>['id'=>1],'cluster'=>['virtualization_type'=>'kvm']],['id'=>124,'name'=>'ct','state'=>false,'node'=>['id'=>2],'cluster'=>['virtualization_type'=>'lxd']]];
$items=VmmanagerConnector::observations($nodes,$hosts);
$r=(new ConnectorResult($items,true))->validated($manifest);
$ok($r->complete && $r->summary($manifest)===['hypervisor_node'=>2,'virtual_machine'=>1,'container'=>1,'cluster'=>0],'typed complete snapshot');
$ok($items[0]['external_id']==='node:1'&&$items[1]['fields']['status']==='maintenance','node identity and maintenance');
$ok($items[2]['external_id']==='host:123'&&$items[2]['parent_external_id']==='node:1'&&$items[2]['fields']['status']==='online','KVM mapping');
$ok($items[3]['type']==='container'&&$items[3]['fields']['status']==='offline','LXD mapping');
$hosts[0]['node']['id']=2;$hosts[0]['name']='renamed';$moved=VmmanagerConnector::observations($nodes,$hosts);
$ok($moved[2]['external_id']===$items[2]['external_id']&&$moved[2]['parent_external_id']==='node:2','migration preserves identity');
$reject(fn()=>VmmanagerConnector::observations([$nodes[0],$nodes[0]],[]));
$reject(fn()=>VmmanagerConnector::observations($nodes,[$hosts[0],$hosts[0]]));
$reject(fn()=>VmmanagerConnector::observations([],[$hosts[0]]));
foreach([0,-1,1.5,'01','1e2',2147483648,true] as $bad) $reject(fn()=>VmmanagerConnector::observations([['id'=>$bad]],[]));
$bad=$hosts[0];$bad['cluster']['virtualization_type']='dummy';$reject(fn()=>VmmanagerConnector::observations($nodes,[$bad]));
$reject(fn()=>VmmanagerConnector::observations(array_fill(0,2001,$nodes[0]),[]));
$reject(fn()=>HttpsTransport::jsonObject('[]'));
$reject(fn()=>HttpsTransport::jsonObject('{broken'));
$ok(HttpsTransport::jsonObject('{"list":[]}')->list===[]&&HttpsTransport::jsonObject('{"list":{}}')->list instanceof stdClass,'JSON array/object distinction');
$ctx=new ConnectorContext('vmmanager','vm.internal',443,'vmmanager_api');
$reject(fn()=>$registry->execute($ctx,'vm.start','api','ignored'),'capability_unavailable');
$reject(fn()=>$registry->execute($ctx,'sync','ssh','ignored'),'permission_denied');
$reject(fn()=>$registry->execute($ctx,'sync','api','{"token":"not allowed whitespace"}'),'connector_failed');
$transport=new HttpsTransport(new EndpointPolicy([],null,true));
$reject(fn()=>$transport->get('vm.internal',443,'/vm/v3/node',"test\r\nX-Evil: value",null,'x-xsrf-token'));
$reject(fn()=>$transport->get('vm.internal',443,'/vm/v3/node','test-token',null,'Cookie'));
$ok(ConnectorTransportException::forStatus(401)->category==='connector_auth_failed'&&ConnectorTransportException::forStatus(429)->category==='connector_rate_limited'&&ConnectorTransportException::forStatus(503)->category==='connector_unavailable','safe remote error classification');
echo "VMmanager runtime smoke: $n PASS\n";
